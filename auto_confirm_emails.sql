-- ============================================
-- Auto-Confirm All User Emails in Supabase Auth
-- ============================================
-- هذا الملف يؤكد جميع البريد الإلكتروني للمستخدمين تلقائياً
-- قم بتشغيله في Supabase SQL Editor
-- ============================================

-- تأكيد جميع البريد الإلكتروني للمستخدمين
UPDATE auth.users
SET email_confirmed_at = COALESCE(email_confirmed_at, NOW())
WHERE email_confirmed_at IS NULL;

-- التحقق من النتيجة
SELECT 
    id,
    email,
    email_confirmed_at,
    created_at
FROM auth.users
WHERE email_confirmed_at IS NULL;

